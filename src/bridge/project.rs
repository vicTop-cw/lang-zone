/// lz.toml 项目清单（build/check 的最小工作集）
#[derive(Debug, Clone)]
pub struct Manifest {
    pub name: String,
    pub version: String,
    pub entry: String,
    /// 三方库依赖：`包名 = "版本约束"`（如 `mylib = "0.1.0"`）。
    pub dependencies: Vec<(String, String)>,
}

/// 顶层帮助文本
pub fn print_help() {
    println!(
        "Lang-Zone compiler (lz) {}\n\
         Usage: lang-zone <file.lz> [flags] | <subcommand> [args]\n\
         \n\
         Subcommands:\n\
         \x20 create <path>     Scaffold a new LZ project (lz.toml + src/main.lz)\n\
         \x20 build  [dir]      Build the project: .lz -> .rs -> executable (incremental)\n\
         \x20 peek   <target>   Show tokens/AST/IR of a file\n\
         \x20 check  [dir]      Type-check the project without emitting code\n\
         \x20 push   [--dry-run]  Publish to local registry\n\
         \x20 emit-bridge-report <tsv>  Audit bridge ledger\n\
         \n\
         Flags (single-file mode): --tokens --ast --emit=... --project --test --std-dir <path>",
        version()
    );
}

fn print_subcommand_help(sub: &str) {
    match sub {
        "create" => println!("create: scaffold a new LZ project\nUsage: lang-zone create <path>"),
        "build" => println!("build: compile the project\nUsage: lang-zone build [dir] [--incremental]"),
        "check" => println!("check: type-check\nUsage: lang-zone check [dir] [--incremental]"),
        "peek" => println!("peek: show tokens/AST/IR\nUsage: lang-zone peek <file.lz> [--tokens|--ast|--emit=ir]"),
        "push" => println!("push: publish\nUsage: lang-zone push [--dry-run] [--registry <path>]"),
        "emit-bridge-report" => println!("emit-bridge-report: audit ledger\nUsage: lang-zone emit-bridge-report <ledger.tsv>"),
        _ => print_help(),
    }
}

// ────────────────────────────── create ──────────────────────────────

pub fn cmd_create(args: &[String]) -> i32 {
    if args.len() < 3 {
        eprintln!("Error: create requires a path argument");
        print_subcommand_help("create");
        return 1;
    }
    let target = Path::new(&args[2]);
    if target.exists() {
        let non_empty = fs::read_dir(target).map(|mut rd| rd.next().is_some()).unwrap_or(false);
        if non_empty {
            eprintln!("Error: {} already exists and is not empty", target.display());
            return 1;
        }
    }
    let src_dir = target.join("src");
    if let Err(e) = fs::create_dir_all(&src_dir) {
        eprintln!("Error: cannot create {}: {}", src_dir.display(), e);
        return 1;
    }
    let name = target.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_else(|| "hello".to_string());
    let manifest = format!("# LZ project manifest\nname = \"{}\"\nversion = \"0.1.0\"\nentry = \"src/main.lz\"\n", name);
    let main_lz = format!("// {name} - generated by `lang-zone create`\ndef main() =\n  print(\"hello from {name}\")\n", name = name);
    let readme = format!("# {name}\nGenerated by `lang-zone create`.\n", name = name);
    for (path, content) in [(target.join("lz.toml"), &manifest), (src_dir.join("main.lz"), &main_lz), (target.join("README.md"), &readme)] {
        if let Err(e) = fs::write(&path, content) {
            eprintln!("Error: cannot write {}: {}", path.display(), e);
            return 1;
        }
    }
    println!("Created LZ project '{}' at {}", name, target.display());
    0
}

// ────────────────────────────── manifest ──────────────────────────────

fn locate_manifest(dir: &Path) -> Option<PathBuf> {
    let direct = dir.join("lz.toml");
    if direct.is_file() { return Some(direct); }
    let parent = dir.parent()?.join("lz.toml");
    if parent.is_file() { return Some(parent); }
    None
}

fn parse_manifest(path: &Path) -> Result<Manifest, String> {
    let text = fs::read_to_string(path).map_err(|e| format!("Cannot read {}: {}", path.display(), e))?;
    let doc = parse_toml(&text).map_err(|e| format!("Manifest parse error in {}: {}", path.display(), e))?;
    let root = doc.get("").cloned().unwrap_or_default();
    let get_str = |key: &str| -> Option<String> {
        root.get(key).and_then(|v| match v { TomlValue::Str(s) => Some(s.clone()), _ => None })
    };
    let mut dependencies: Vec<(String, String)> = Vec::new();
    if let Some(deps) = doc.get("dependencies") {
        let mut names: Vec<&String> = deps.keys().collect();
        names.sort();
        for dep_name in names {
            let version = match deps.get(dep_name) {
                Some(TomlValue::Str(v)) => Some(v.clone()),
                Some(TomlValue::InlineTable(t)) => match t.get("version") {
                    Some(TomlValue::Str(v)) => Some(v.clone()),
                    _ => None,
                },
                _ => None,
            };
            if let Some(v) = version { dependencies.push((dep_name.clone(), v)); }
        }
    }
    Ok(Manifest {
        name: get_str("name").unwrap_or_else(|| "app".to_string()),
        version: get_str("version").unwrap_or_else(|| "0.1.0".to_string()),
        entry: get_str("entry").unwrap_or_else(|| "src/main.lz".to_string()),
        dependencies,
    })
}

// ────────────────────────────── build / check 共用 ──────────────────────────────

struct ProjectPaths {
    root: PathBuf,
    manifest: Manifest,
    entry: PathBuf,
    build_dir: PathBuf,
    rs_out: PathBuf,
    exe_out: PathBuf,
}

impl ProjectPaths {
    fn resolve(dir: &Path) -> Result<Self, String> {
        let manifest_path = locate_manifest(dir).ok_or_else(|| format!("Error: lz.toml not found in {} or its parent directory", dir.display()))?;
        let manifest = parse_manifest(&manifest_path)?;
        let root = manifest_path.parent().unwrap_or(Path::new(".")).to_path_buf();
        let entry = if Path::new(&manifest.entry).is_absolute() { PathBuf::from(&manifest.entry) } else { root.join(&manifest.entry) };
        let build_dir = root.join("build");
        let exe_name = format!("{}.exe", manifest.name);
        let rs_name = format!("{}.rs", manifest.name);
        Ok(ProjectPaths { root, manifest, entry, rs_out: build_dir.join(rs_name), exe_out: build_dir.join(exe_name), build_dir })
    }
}

fn compile_project_to_ir(paths: &ProjectPaths, std_dir: Option<&Path>) -> Result<(crate::ir::IrModule, usize), String> {
    let entry = &paths.entry;
    let mut pc = ProjectCompiler::new(paths.root.clone(), std_dir.map(Path::to_path_buf));
    let mut merged = pc.compile(entry)?;
    let module_count = pc.unit_count();
    if merged.file_path.is_none() {
        merged.file_path = Some(entry.canonicalize().map(|p| p.display().to_string()).unwrap_or_else(|_| entry.display().to_string()));
    }
    let errs = crate::semantic_check::check_module(&merged);
    if !errs.is_empty() { return Err(errs.join("\n")); }
    let ir = build_ir(&merged).map_err(|e| format!("IR build error in {}: {}", entry.display(), e))?;
    for w in crate::ir::builder::take_tco_warnings() { eprintln!("{}", w); }
    Ok((ir, module_count))
}

fn source_hashes(entry: &Path) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut seen = std::collections::HashSet::new();
    let mut stack = vec![entry.to_path_buf()];
    while let Some(p) = stack.pop() {
        let canon = p.canonicalize().unwrap_or(p.clone());
        if !seen.insert(canon.clone()) { continue; }
        if let Ok(h) = crate::cache::content_hash(&canon) { out.push((canon.display().to_string(), h)); }
        if let Ok(src) = fs::read_to_string(&canon) {
            let dir = canon.parent().map(Path::to_path_buf).unwrap_or_default();
            for line in src.lines() {
                let t = line.trim_start();
                let mod_name = if let Some(rest) = t.strip_prefix("import ") { rest.split_whitespace().next() } else if let Some(rest) = t.strip_prefix("from ") { rest.split_whitespace().next() } else { None };
                if let Some(m) = mod_name {
                    if m != "std" && !m.contains('.') {
                        let dep = dir.join(format!("{}.lz", m));
                        if dep.is_file() { stack.push(dep); }
                    }
                }
            }
        }
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

fn rustc_compile(rs: &Path, exe: &Path) -> Result<(), String> {
    let started = std::time::Instant::now();
    let builtins = crate::frontend::bootstrap_emit::builtins_rlib_path();
    let mut cmd = crate::frontend::bootstrap_emit::rustc_command();
    cmd.args(["--edition", "2021"]).arg(rs).arg("--extern").arg(format!("lz_builtins={}", builtins.display())).arg("-L").arg(format!("dependency={}", builtins.parent().unwrap().join("deps").display())).arg("-o").arg(exe);
    if rustc_incremental_enabled() {
        let inc_dir = exe.with_extension("rustc-incremental");
        cmd.arg("-C").arg(format!("incremental={}", inc_dir.display()));
    }
    if crate::ir::codegen::release_mode() { cmd.arg("-C").arg("opt-level=3"); }
    let out = cmd.output().map_err(|e| format!("Failed to run rustc: {}", e))?;
    let ms = started.elapsed().as_secs_f64() * 1000.0;
    if rustc_timing_enabled() { eprintln!("[build] rustc: {:.0} ms", ms); }
    if out.status.success() { Ok(()) } else { Err(String::from_utf8_lossy(&out.stderr).to_string()) }
}

static RUSTC_TIMING: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

pub fn rustc_timing_enabled() -> bool {
    if RUSTC_TIMING.load(std::sync::atomic::Ordering::Relaxed) { return true; }
    match std::env::var("LZ_TIME") {
        Ok(v) => { let v = v.trim().to_ascii_lowercase(); v == "1" || v == "true" || v == "on" }
        Err(_) => false,
    }
}

fn rustc_incremental_enabled() -> bool {
    match std::env::var("LZ_RUSTC_INCREMENTAL") {
        Ok(v) => { let v = v.trim().to_ascii_lowercase(); !(v == "0" || v == "false" || v == "off" || v == "no") }
        Err(_) => true,
    }
}

// ────────────────────────────── build ──────────────────────────────

pub fn cmd_build(args: &[String]) -> i32 {
    if args.iter().any(|a| a == "--stats") { RUSTC_TIMING.store(true, std::sync::atomic::Ordering::Relaxed); }
    let (dir_arg, incremental_flag) = parse_dir_and_flags(args, "build");
    let incremental = incremental_flag && !args.iter().any(|a| a == "--no-incremental");
    let dir = Path::new(&dir_arg);
    let paths = match ProjectPaths::resolve(dir) { Ok(p) => p, Err(e) => { eprintln!("{}", e); return 1; } };
    if !paths.manifest.dependencies.is_empty() {
        match crate::util::registry::find_registry_root(&paths.root) {
            Some(root) => match crate::util::registry::resolve_dependencies(&root, &paths.manifest.dependencies) {
                Ok(_) => {}
                Err(e) => { eprintln!("Error: {}", e); return 1; }
            },
            None => {
                eprintln!("Error: lz.toml declared {} dependencies but no registry found.", paths.manifest.dependencies.len());
                return 1;
            }
        }
    }
    let std_dir = args.iter().position(|a| a == "--std-dir").and_then(|i| args.get(i + 1)).map(PathBuf::from);
    if incremental {
        let cache_dir = paths.build_dir.join(".lzcache");
        if let Ok(Some(entry)) = CacheEntry::load(&cache_dir, &paths.entry) {
            if entry.is_fresh(&paths.entry, &cache_dir) && !entry.output.is_empty() {
                let cached_rs = cache_dir.join(&entry.output);
                if cached_rs.exists() {
                    if !paths.rs_out.exists() || fs::metadata(&paths.rs_out).and_then(|m| m.modified()).ok() != fs::metadata(&cached_rs).and_then(|m| m.modified()).ok() {
                        if let Some(dir) = paths.rs_out.parent() { let _ = fs::create_dir_all(dir); }
                        if fs::copy(&cached_rs, &paths.rs_out).is_err() {} else { println!("Incremental hit: lzc stage skipped"); }
                    } else { println!("Incremental hit: lzc stage skipped"); }
                    let exe_fresh = paths.exe_out.exists() && match (fs::metadata(&paths.exe_out).and_then(|m| m.modified()), fs::metadata(&paths.rs_out).and_then(|m| m.modified())) {
                        (Ok(a), Ok(b)) => a >= b, _ => false,
                    };
                    if exe_fresh { return 0; }
                    if let Err(e) = rustc_compile(&paths.rs_out, &paths.exe_out) { eprintln!("rustc error:\n{}", e); return 1; }
                    return 0;
                }
            }
        }
    }
    let (ir, module_count) = match compile_project_to_ir(&paths, std_dir.as_deref()) {
        Ok(v) => v, Err(e) => { eprintln!("{}", e); return 1; }
    };
    let mut cg = IrCodeGen::new();
    cg.set_embed_stem(&paths.entry.display().to_string());
    let (rust_code, mut registry) = cg.generate_with_bridge(&ir);
    if !cg.embed_targets().is_empty() {
        crate::embed::emit::emit_embed_artifacts(cg.embed_targets(), args.iter().any(|a| a == "--embed-build"), false, Some(paths.root.as_path()));
    }
    if let Err(e) = fs::create_dir_all(&paths.build_dir) { eprintln!("Error: cannot create {}: {}", paths.build_dir.display(), e); return 1; }
    if let Err(e) = fs::write(&paths.rs_out, &rust_code) { eprintln!("Error: cannot write {}: {}", paths.rs_out.display(), e); return 1; }
    println!("Generated {} -> {} ({} modules)", paths.entry.display(), paths.rs_out.display(), module_count);
    if registry.symbol_count() > 0 {
        let ledger_path = paths.build_dir.join("bridge-ledger.tsv");
        let _ = registry.set_ledger_path(&ledger_path);
        let _ = registry.ledger_mut().flush();
        println!("Bridge registry: {} symbol(s) registered -> {}", registry.symbol_count(), ledger_path.display());
    }
    if let Err(e) = rustc_compile(&paths.rs_out, &paths.exe_out) { eprintln!("rustc error:\n{}", e); return 1; }
    println!("Built {} {} -> {}", paths.manifest.name, paths.manifest.version, paths.exe_out.display());
    let hashes = source_hashes(&paths.entry);
    let entry_hash = hashes.iter().find(|(p, _)| Path::new(p) == paths.entry.canonicalize().unwrap_or_else(|_| paths.entry.clone())).map(|(_, h)| h.clone()).or_else(|| crate::cache::content_hash(&paths.entry).ok()).unwrap_or_default();
    let entry_saved = CacheEntry {
        hash: entry_hash,
        deps: hashes.iter().filter(|(p, _)| Path::new(p) != paths.entry.canonicalize().unwrap_or_else(|_| paths.entry.clone())).map(|(p, h)| (p.clone(), h.clone())).collect(),
        output: format!("../{}", paths.rs_out.file_name().unwrap_or_default().to_string_lossy()),
    };
    let cache_dir = paths.build_dir.join(".lzcache");
    let _ = entry_saved.save(&cache_dir, &paths.entry);
    0
}

// ────────────────────────────── check ──────────────────────────────

pub fn cmd_check(args: &[String]) -> i32 {
    let (dir_arg, incremental) = parse_dir_and_flags(args, "check");
    let dir = Path::new(&dir_arg);
    let paths = match ProjectPaths::resolve(dir) { Ok(p) => p, Err(e) => { eprintln!("{}", e); return 1; } };
    let check_cache = paths.build_dir.join(".lzcheck");
    let current_hashes = source_hashes(&paths.entry);
    let hash_line = hashes_line(&current_hashes);
    if incremental {
        if let Ok(cached) = fs::read_to_string(&check_cache) {
            let cached_hash = cached.lines().find_map(|l| l.strip_prefix("hashes=")).unwrap_or("");
            if cached_hash == hash_line {
                println!("check ok (incremental hit): {} modules, {} items", count_modules(&current_hashes), count_items(&paths));
                return 0;
            }
        }
    }
    let (ir, module_count) = match compile_project_to_ir(&paths, None) {
        Ok(v) => v, Err(e) => { eprintln!("{}", e); return 1; }
    };
    let duck_errors = check_duck_satisfaction(&ir);
    if !duck_errors.is_empty() {
        for e in &duck_errors { eprintln!("Duck check error: {}", e); }
        return 1;
    }
    if args.iter().any(|a| a == "--rustc") {
        let mut cg = IrCodeGen::new();
        let (rust_code, _) = cg.generate_with_bridge(&ir);
        if let Err(e) = fs::create_dir_all(&paths.build_dir) { eprintln!("Error: cannot create {}: {}", paths.build_dir.display(), e); return 1; }
        if let Err(e) = fs::write(&paths.rs_out, &rust_code) { eprintln!("Error: cannot write {}: {}", paths.rs_out.display(), e); return 1; }
        if let Err(e) = rustc_metadata_check(&paths.rs_out) { eprintln!("rustc error:\n{}", e); return 1; }
    }
    let item_count = ir.items.len();
    let summary = format!("# lzcheck summary\nhashes={}\nmodules={}\nitems={}\n", hash_line, module_count, item_count);
    let _ = fs::create_dir_all(&paths.build_dir);
    if let Err(e) = fs::write(&check_cache, &summary) { eprintln!("Warning: cannot write {}: {}", check_cache.display(), e); }
    println!("check ok: {} modules, {} items", module_count, item_count);
    0
}

fn rustc_metadata_check(rs: &Path) -> Result<(), String> {
    let started = std::time::Instant::now();
    let builtins = crate::frontend::bootstrap_emit::builtins_rlib_path();
    let out = crate::frontend::bootstrap_emit::rustc_command().args(["--edition", "2021", "--emit=metadata", "--crate-type", "lib"]).arg(rs).arg("--extern").arg(format!("lz_builtins={}", builtins.display())).output().map_err(|e| format!("Failed to run rustc: {}", e))?;
    if rustc_timing_enabled() { eprintln!("[check] rustc --emit=metadata: {:.0} ms", started.elapsed().as_secs_f64() * 1000.0); }
    if out.status.success() { Ok(()) } else { Err(String::from_utf8_lossy(&out.stderr).to_string()) }
}

// ────────────────────────────── peek（简化版，不调用 compile_main）──────────────────────────────

/// peek <file.lz>：输出 tokens/AST/IR 三视图。
/// M3 简化版：直接 lex→parse→build_ir→print，不调用 compile_main（避免循环依赖）。
pub fn cmd_peek(args: &[String]) -> i32 {
    if args.len() < 3 || args[2] == "--help" || args[2] == "-h" {
        print_subcommand_help("peek");
        return if args.len() < 3 { 1 } else { 0 };
    }
    let target = Path::new(&args[2]);
    if !target.is_file() {
        eprintln!("Error: cannot peek {}: no such file", target.display());
        return 1;
    }
    let source = fs::read_to_string(target).unwrap_or_else(|e| {
        eprintln!("Error reading {}: {}", target.display(), e);
        return String::new();
    });
    if source.is_empty() { return 1; }
    let show_tokens = args.iter().any(|a| a == "--tokens");
    let show_ast = args.iter().any(|a| a == "--ast");
    // Lex
    let mut lexer = crate::lexer::Lexer::new(&source);
    let tokens = lexer.tokenize();
    if show_tokens {
        for t in &tokens { println!("{:?}", t); }
        return 0;
    }
    // Parse
    let mut parser = crate::parser::Parser::new(tokens);
    let ast = match parser.parse_module() {
        Ok(a) => a,
        Err(e) => { eprintln!("Parse error: {}", e); return 1; }
    };
    if show_ast {
        println!("{:#?}", ast);
        return 0;
    }
    // Build IR（默认输出）
    match build_ir(&ast) {
        Ok(ir) => { println!("{}", ir); 0 }
        Err(e) => { eprintln!("IR build error: {}", e); 1 }
    }
}

// ────────────────────────────── push ──────────────────────────────

pub fn cmd_push(args: &[String]) -> i32 {
    let mut dir_arg = String::from(".");
    let mut dry_run = false;
    let mut registry: Option<String> = None;
    let mut i = 2;
    while i < args.len() {
        match args[i].as_str() {
            "--help" | "-h" => { print_subcommand_help("push"); return 0; }
            "--dry-run" => dry_run = true,
            "--registry" => {
                if i + 1 >= args.len() { eprintln!("Error: --registry requires a path"); return 1; }
                registry = Some(args[i + 1].clone());
                i += 1;
            }
            a if !a.starts_with('-') && dir_arg == "." => dir_arg = a.to_string(),
            _ => { eprintln!("Error: unknown push argument {}", args[i]); return 1; }
        }
        i += 1;
    }
    let dir = Path::new(&dir_arg);
    let paths = match ProjectPaths::resolve(dir) { Ok(p) => p, Err(e) => { eprintln!("{}", e); return 1; } };
    let (_ir, module_count) = match compile_project_to_ir(&paths, None) {
        Ok(v) => v, Err(e) => { eprintln!("Preflight failed: {}", e); return 1; }
    };
    let reg_dir = Path::new(registry.as_deref().unwrap_or("local-registry")).to_path_buf();
    let pkg_dir = reg_dir.join(&paths.manifest.name).join(&paths.manifest.version);
    if pkg_dir.exists() {
        eprintln!("Error: version conflict: {} {} already published", paths.manifest.name, paths.manifest.version);
        return 1;
    }
    let hashes = source_hashes(&paths.entry);
    let mut checksum_input = format!("name={}\nversion={}\nmodules={}\n", paths.manifest.name, paths.manifest.version, module_count);
    for (p, h) in &hashes { checksum_input.push_str(&format!("{} {}\n", h, p)); }
    use std::hash::{Hash, Hasher};
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    checksum_input.hash(&mut hasher);
    let checksum = format!("{:016x}", hasher.finish());
    if dry_run {
        println!("[dry-run] would publish {} {} -> {} (checksum {})", paths.manifest.name, paths.manifest.version, pkg_dir.display(), checksum);
        println!("[dry-run] {} modules, {} source files", module_count, hashes.len());
        return 0;
    }
    // 事务性发布
    let tmp = reg_dir.join(format!(".tmp-{}-{}-{}", paths.manifest.name, paths.manifest.version, std::process::id()));
    let tmp_pkg = tmp.join(&paths.manifest.name).join(&paths.manifest.version);
    let build_result = (|| -> Result<(), String> {
        fs::create_dir_all(&tmp_pkg).map_err(|e| e.to_string())?;
        fs::write(tmp_pkg.join("checksum.txt"), format!("{}\n{}", checksum, checksum_input)).map_err(|e| e.to_string())?;
        let manifest_text = fs::read_to_string(&paths.root.join("lz.toml")).map_err(|e| e.to_string())?;
        fs::write(tmp_pkg.join("lz.toml"), manifest_text).map_err(|e| e.to_string())?;
        fs::create_dir_all(tmp_pkg.join("src")).map_err(|e| e.to_string())?;
        let src_dir = paths.entry.parent().unwrap_or(Path::new("."));
        let mut copied = 0usize;
        let mut stack = vec![(src_dir.to_path_buf(), PathBuf::new())];
        let mut seen = std::collections::HashSet::new();
        while let Some((p, rel_prefix)) = stack.pop() {
            if !seen.insert(p.clone()) { continue; }
            if let Ok(rd) = fs::read_dir(&p) {
                for e in rd.flatten() {
                    let ep = e.path();
                    if ep.is_dir() && ep.file_name().map(|n| n != "build").unwrap_or(false) {
                        stack.push((ep.clone(), rel_prefix.join(ep.file_name().unwrap_or_default())));
                    } else if ep.extension().map(|x| x == "lz").unwrap_or(false) {
                        let rel = rel_prefix.join(ep.file_name().unwrap_or_default());
                        let dest = tmp_pkg.join("src").join(&rel);
                        if let Some(parent) = dest.parent() { fs::create_dir_all(parent).map_err(|e| e.to_string())?; }
                        fs::copy(&ep, &dest).map_err(|e| e.to_string())?;
                        copied += 1;
                    }
                }
            }
        }
        fs::write(tmp_pkg.join("files.txt"), format!("copied={}\n", copied)).map_err(|e| e.to_string())?;
        Ok(())
    })();
    if let Err(e) = build_result {
        let _ = fs::remove_dir_all(&tmp);
        eprintln!("Error: publish failed: {}", e);
        return 1;
    }
    if let Some(parent) = pkg_dir.parent() { if let Err(e) = fs::create_dir_all(parent) { let _ = fs::remove_dir_all(&tmp); eprintln!("Error: cannot create registry: {}", e); return 1; } }
    if let Err(e) = fs::rename(&tmp_pkg, &pkg_dir) { let _ = fs::remove_dir_all(&tmp); eprintln!("Error: publish failed: {}", e); return 1; }
    let _ = fs::remove_dir_all(&tmp);
    println!("Published {} {} -> {} (checksum {})", paths.manifest.name, paths.manifest.version, pkg_dir.display(), checksum);
    0
}

// ────────────────────────────── 小工具 ──────────────────────────────

fn parse_dir_and_flags(args: &[String], sub: &str) -> (String, bool) {
    let mut dir_arg = String::from(".");
    let mut incremental = false;
    for a in args.iter().skip(2) {
        if a == "--incremental" { incremental = true; }
        else if a == "--hide-type-annotations" { crate::ir::codegen::set_hide_type_annotations(true); }
        else if a == "--hide-module-meta" { crate::ir::codegen::set_hide_module_meta(true); }
        else if a == "--hide-return-keyword" { crate::ir::codegen::set_hide_return_keyword(true); }
        else if a == "--release" { crate::ir::codegen::set_release_mode(true); }
        else if a == "--no-tco" { crate::ir::builder::set_tco_enabled(false); }
        else if a == "--help" || a == "-h" { print_subcommand_help(sub); std::process::exit(0); }
        else if !a.starts_with('-') && dir_arg == "." { dir_arg = a.clone(); }
    }
    (dir_arg, incremental)
}

fn hashes_line(hashes: &[(String, String)]) -> String {
    let mut s = String::new();
    for (p, h) in hashes { s.push_str(p); s.push(':'); s.push_str(h); s.push(';'); }
    s
}

fn count_modules(hashes: &[(String, String)]) -> usize { hashes.len() }

fn count_items(paths: &ProjectPaths) -> usize {
    let cache = paths.build_dir.join(".lzcheck");
    fs::read_to_string(&cache).ok().and_then(|c| c.lines().find_map(|l| l.strip_prefix("items=").and_then(|v| v.parse::<usize>().ok()))).unwrap_or(0)
}

// ────────────────────────────── emit-bridge-report ──────────────────────────────

pub fn cmd_emit_bridge_report(args: &[String]) -> i32 {
    if args.len() < 3 || args[2] == "--help" || args[2] == "-h" {
        print_subcommand_help("emit-bridge-report");
        return if args.len() < 3 { 1 } else { 0 };
    }
    let target = Path::new(&args[2]);
    if !target.is_file() {
        eprintln!("Error: cannot audit {}: no such ledger file", target.display());
        return 1;
    }
    let report = crate::bridge::ledger::Ledger::report_path(target);
    print!("{}", report.render());
    0
}

